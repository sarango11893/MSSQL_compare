namespace SqlSuite.Core.Models;

/// <summary>Metadata for a single table column, derived from the DacFx model.</summary>
public sealed class ColumnSchemaInfo
{
    public string Name { get; init; } = string.Empty;

    /// <summary>Type name as reported by DacFx, for example <c>nvarchar</c> or <c>decimal</c>.</summary>
    public string DataTypeName { get; init; } = string.Empty;

    /// <summary>Length in characters / bytes as reported by DacFx. Zero means "not applicable".</summary>
    public int MaxLength { get; init; }

    public bool IsMax { get; init; }

    public int Precision { get; init; }

    public int Scale { get; init; }

    public bool IsNullable { get; init; }

    public bool IsIdentity { get; init; }

    /// <summary>Computed columns have an expression instead of a stored data type.</summary>
    public bool IsComputed { get; init; }

    /// <summary><c>rowversion</c> / <c>timestamp</c> columns are generated by the engine.</summary>
    public bool IsRowVersion { get; init; }

    /// <summary>Columns that a script can write to.</summary>
    public bool IsWritable => !IsComputed && !IsRowVersion;

    /// <summary><see langword="true"/> for <c>nchar</c> / <c>nvarchar</c> / <c>ntext</c> style types.</summary>
    public bool IsUnicode =>
        DataTypeName.Equals("nvarchar", StringComparison.OrdinalIgnoreCase) ||
        DataTypeName.Equals("nchar", StringComparison.OrdinalIgnoreCase) ||
        DataTypeName.Equals("ntext", StringComparison.OrdinalIgnoreCase) ||
        DataTypeName.Equals("sysname", StringComparison.OrdinalIgnoreCase);

    public string TypeDescription
    {
        get
        {
            if (string.IsNullOrEmpty(DataTypeName))
                return string.Empty;

            if (IsMax)
                return $"{DataTypeName}(max)";

            if (Precision > 0)
                return $"{DataTypeName}({Precision},{Scale})";

            if (MaxLength > 0)
                return $"{DataTypeName}({MaxLength})";

            return DataTypeName;
        }
    }

    public override string ToString() => $"{Name} {TypeDescription}";
}
